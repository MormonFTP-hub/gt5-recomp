#!/usr/bin/env python3
"""Cut w018CAD00's routine 0xF6C0 (the batch cull for mirror records) out of the job's lifted source, for
native_cad00.c.

native_cad00.c runs 0xF6C0 as one native call: the routine's own statements from this copy's lift, with its
hot loops -- the vertex transform 0xF970, the bounding box 0xFA78 and the vertex-in-record test 0xFD60 (about
85 % of the routine's time on real batches) -- taken by native code when they can be. This script copies the
lifted function's statements unchanged but for:
  * the interrupt checks at labels are dropped (the native call only starts with no interrupt pending; one
    that arrives later is taken when the call returns, as for every native function of this image);
  * the function is renamed cad_f6c0_lift(ctx) (static, in native_cad00.c);
  * just before each of those loops' label a line CAD_F6_LOOPn is inserted (the way in; the loop's own branch
    goes to the label), and CAD_F6_LOOPn_DONE after the loop's closing branch where the loop falls out:
    native_cad00.c defines them (the loop's groups natively, its last passes lifted, see there);
  * after every label, CAD_AT(address) (nothing in the game; the harness's time per region).
The statements are found by the function's name and labels, not by line numbers; the shape the native code
relies on (the labels, each loop entered only from before it and closed by its one branch back) is checked,
and the script fails if it is not there.

Usage: gen_cad00_f6c0.py <spu_recomp.c> <out_dir>      writes <out_dir>/cad00_f6c0_lift.inc
"""
import re
import sys
from pathlib import Path

FUNC = re.compile(r"^SPU_SV void gt5_w018CAD00_spu_func_0000F6C0(?:_orig)?_sv\(spu_context\* ctx\) \{\s*$")
INTR = re.compile(r"^\s*if \(ctx->int_enable && \(ctx->event_status & ctx->event_mask\)\) \{.*return; \}\s*$")
LABEL = re.compile(r"^loc_([0-9A-F]{8}):\s*$")
# (label, its closing branch, macro on the way in, macro after the loop or None)
LOOPS = [
    ("loc_0000F970", re.compile(r"^\s*if \(spu_h0\(r47\) != 0\) \{ goto loc_0000F970; \}\s*$"), "CAD_F6_LOOP2", "CAD_F6_LOOP2_DONE"),
    ("loc_0000FA78", re.compile(r"^\s*if \(spu_w0\(r21\) != 0\) \{ goto loc_0000FA78; \}\s*$"), "CAD_F6_LOOP3", None),
    ("loc_0000FD60", re.compile(r"^\s*if \(spu_w0\(r45\) != 0\) \{ goto loc_0000FD60; \}\s*$"), "CAD_F6_LOOP4", "CAD_F6_LOOP4_DONE"),
]
NEED = ["loc_0000F828", "loc_0000F970", "loc_0000FA78", "loc_0000FB40", "loc_0000FD60", "loc_0000FE78", "loc_0000FF00",
        "loc_00010050"]


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    src = Path(sys.argv[1]).read_text(encoding="latin-1").splitlines()
    out_dir = Path(sys.argv[2])
    start = next((i for i, l in enumerate(src) if FUNC.match(l)), None)
    if start is None:
        raise SystemExit("gen_cad00_f6c0: the lifted function for 0xF6C0 is not in " + sys.argv[1])
    end = next(i for i in range(start + 1, len(src)) if src[i] == "}")
    body = src[start + 1:end]
    labels = [m.group(0).strip()[:-1] for m in (LABEL.match(l) for l in body) if m]
    for n in NEED:
        if n not in labels:
            raise SystemExit(f"gen_cad00_f6c0: label {n} missing in the lifted 0xF6C0: the lift is not the one this was written for")
    for lab, close, _, _ in LOOPS:
        if sum(1 for l in body if close.match(l)) != 1 or sum(1 for l in body if f"goto {lab};" in l) != 1:
            raise SystemExit(f"gen_cad00_f6c0: the loop at {lab} is not entered and closed as expected")
    out = ["/* generated by gen_cad00_f6c0.py from " + Path(sys.argv[1]).name + ": w018CAD00 0xF6C0, lifted statements */",
           "static SPU_SV void cad_f6c0_lift(spu_context* ctx) {"]
    dropped = 0
    for l in body:
        if INTR.match(l):
            dropped += 1
            continue
        m = LABEL.match(l)
        for lab, close, enter, done in LOOPS:
            if m and lab == "loc_" + m.group(1):
                out.append(f"        {enter};")
        out.append(l)
        if m:
            out.append(f"        CAD_AT(0x{m.group(1)});")
        for lab, close, enter, done in LOOPS:
            if done and close.match(l):
                out.append(f"        {done};")
    out.append("}")
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "cad00_f6c0_lift.inc").write_text("\n".join(out) + "\n", encoding="latin-1")
    print(f"gen_cad00_f6c0: {len(body)} lines, {dropped} interrupt checks dropped -> {out_dir / 'cad00_f6c0_lift.inc'}")


if __name__ == "__main__":
    main()
